namespace WayCoder.UI.Shared;

/// <summary>
/// 传感器的纯数学 —— **放在共享层**（`UI/Shared/`，主工程与 MAUI 都编译）。
///
/// <para>
/// 为什么不让各平台自己算：Android 的融合姿态给的是**旋转向量（四元数）**，
/// 要转成欧拉角才符合本仓的契约（`SENSOR` 的 `Rotation` 三档是俯仰/翻滚/方位）。
/// 这段换算如果写在 `#if ANDROID` 里面，**自测碰不到它**（桌面不编 Android 分支），
/// 而它的错法全是"符号反了""顺序换了一个"，**在真机上看起来就是"倾斜方向不对"** ——
/// 那是最难查的一类（本仓在编辑器网格那块吃过两轮同样的亏）。
/// 放这儿则桌面自测能逐条钉住。
/// </para>
///
/// <para>
/// ⚠ iOS 那边**不用**它：`CMDeviceMotion.Attitude` 直接给的就是欧拉角（弧度）。
/// 两条路各用各的平台 API 是对的（平台的活给平台干），
/// 但**契约里的顺序与符号**两边必须一致 —— 也就是这里这几个返回值。
/// </para>
/// </summary>
public static class SensorMath
{
    /// <summary>
    /// 单位四元数 → 欧拉角（**弧度**），按契约顺序 `(俯仰 pitch, 翻滚 roll, 方位 yaw)`。
    ///
    /// <para>
    /// 对应设备坐标系：`x` = 屏幕向右、`y` = 屏幕向上、`z` = **屏幕朝外**（指向用户）。
    /// 这正是 Android 旋转向量与 iOS `attitude` 用的那套，所以不需要换轴。
    /// </para>
    ///
    /// <para>
    /// ⚠ **俯仰要钳**：`asin` 的输入是 `2(wy − zx)`，而浮点误差会让它落到 `[-1,1]` 外面
    /// （实测在接近 ±90° 时是常态）⇒ 不钳就是 `NaN`，而 `NaN` 传下去会变成
    /// "角度一直是 0"（见 `ScaleSensor` 里那条同样的处置）。手机立起来玩就会撞上。
    /// </para>
    ///
    /// <para>
    /// ⚠ **方位角不保证长期稳定**：没有磁力计的设备上它靠陀螺仪积分，会慢慢漂。
    /// 这是平台的事，不是这段数学的事 —— 但契约的文档里要写明，免得有人拿它当指南针。
    /// </para>
    /// </summary>
    public static (double Pitch, double Roll, double Yaw) QuaternionToEuler(double x, double y, double z, double w)
    {
        // 归一化：平台的旋转向量**理论上**是单位四元数，但实测有轻微偏移，
        // 而下面的公式假设它是单位的（不归一化时俯仰会随姿态缓慢漂）。
        var norm = Math.Sqrt(x * x + y * y + z * z + w * w);
        if (norm <= 1e-9) return (0, 0, 0);
        x /= norm; y /= norm; z /= norm; w /= norm;

        // ⚠⚠ **三个量的顺序要与"绕哪条轴"对上，这是本函数唯一的坑。**
        //
        //   标准分解式里那个 `asin` 项，名字虽然常被叫成 pitch，**几何上它是"绕 y 轴的角"**；
        //   而"绕 x 轴的角"在那个式子里是**第一个 `atan2`**。契约要的是
        //   `(绕 x, 绕 y, 绕 z)`（即 俯仰 / 翻滚 / 方位），所以要**按轴取**，
        //   不能按公式里那个惯用名去对号入座 —— 实测写反过一次，
        //   症状是"抬头它报翻滚、歪头它报俯仰"，而**两个数都在合理范围内**，
        //   看着完全不像坏了（自测里 `绕 x 转 90°` 那两条就是为了钉住它）。
        var aboutY = Math.Asin(Math.Clamp(2 * (w * y - z * x), -1.0, 1.0));
        // ⚠ 两个 `atan2` 的分母要**先看是不是 ~0**：正负 90°（万向节锁）附近它数学上是 0，
        //   而浮点会给出 `-2.2e-16` 这种**有符号的微小值** ⇒ `atan2(0, 负数)` 返回 **π**、
        //   `atan2(0, 正数)` 返回 0。同一个姿态在锁点两侧因此会**突然跳 180°**。
        //   （实测：绕 y 转正好 90° 时，这里返回过 `(π, π/2, π)` —— 与直觉的
        //   `(0, π/2, 0)` 表示**同一个旋转**，但那个 π 是数值噪声，不是角度。）
        //   锁点上绕另外两轴的角本来就**不是唯一确定的**（这正是"万向节锁"的含义），
        //   所以这里按惯例**取 0**，把函数在锁点附近变成连续的。
        //   ⚠ 判据是**分子分母同时接近 0**（真正的 0/0），不能只看分母 ——
        //   分母单独接近 0 是**正常**的（`atan2(1, 0)` 就是 90°，那是绕 x 转 90° 的情形）。
        var nx = 2 * (w * x + y * z);
        var dx = 1 - 2 * (x * x + y * y);
        var nz = 2 * (w * z + x * y);
        var dz = 1 - 2 * (y * y + z * z);
        var aboutX = (NearZero(nx) && NearZero(dx)) ? 0 : Math.Atan2(nx, dx);
        var aboutZ = (NearZero(nz) && NearZero(dz)) ? 0 : Math.Atan2(nz, dz);
        return (aboutX, aboutY, aboutZ);
    }

    /// <summary>`atan2` 的分母"是不是该当成 0"（见上面万向节锁那段）。
    /// 取 1e-12：真实姿态下分母是量级 1 的数，只有锁点上才会掉到这个量级以下。</summary>
    private static bool NearZero(double v) => Math.Abs(v) < 1e-12;
}
