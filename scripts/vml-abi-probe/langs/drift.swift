// 栈漂移探针（Swift）：循环里反复调外部库函数（ipow）。判据：`DRIFT=126`（2^1+…+2^6）。
// 反序得 91（i^2 之和）、第 2 参丢得 6（ipow(2,0)=1）。
//
// 照 corpus/swift/skel.swift：状态放函数内局部（模块级标量读出来是垃圾，见 §4.5 的两条写法约束）。
// print 逐参输出、不插分隔符、末尾补一次换行 ⇒ 两个参数正好拼成一行。
//
// ⚠ 审计记「Swift 的被调方前 4 参读 R0-R3」。v0.96.195 的 §4.5 续已修掉「第 5 个参数起全是
//    第 1 个参数的值」那一条（8 参的 overlap 实测逐个精确）—— 那两处是否同一处、前 4 参还有没有
//    别的问题，这条 2 参探针**照不到**（只用到前 2 个）。真要覆盖得写 5 参以上的探针。
func main() {
    var s = 0
    var i = 1
    while i <= 6 {
        s = s + ipow(2, i)
        i = i + 1
    }
    print("DRIFT=", s)
}
