/* p3_local_after_lib —— **栈平衡判据**：调过库函数之后，调用方的局部必须一字未动。
 *
 * 这是整份判据里最关键的一条，也是「调用约定统一」这件事的直接靶子。
 *
 * ── 根因（2026-09-17 实测确认，不是推测）────────────────────────────────
 *
 * 库里的 builtins 家族（`println_int` / `print_str` …）是**被调方清栈**，
 * 尾声长这样（`Lib/shared/builtins.vml`）：
 *
 *       push R15 / push R12 / move R12 R13
 *       syscall #6                 ; 参数直接吃 R0，从不读 [R12+12]
 *       ...
 *       move R1 @13                ; 存返回地址
 *       add R13 #8                 ; ← 被调方清掉「返回地址 + 1 个参数槽」
 *       push R1 / ret
 *
 * 而 C 前端的 cdecl 路径**调用方又清一次**（调用点后面跟 `add R13 #4`）
 * ⇒ **每次调用净 +4 字节**。SP 一路向上爬进调用方自己的栈帧，把局部**覆盖掉**。
 *
 * 症状之所以诡异：**同一个变量连续读两遍能读出不同的值**（实测 0 然后 242），
 * 因为读第一遍时还没被踩、中间又发生了一次调用的 push。
 *
 * ── 这个探针为什么长这样 ──────────────────────────────────────────────
 *
 * ⚠ 漂移是 **+4/次**，要爬到某个局部头上才踩得到 ⇒ 「变量少 + 调用少」的写法
 * **测不出来**（第一版就是这么假绿的）。这里刻意用
 * **8 个元素的局部数组 + 8 次库调用 + 一个循环**：
 * 漂移量（32 字节）必定穿过整个栈帧，而且一旦循环变量被踩，
 * 计数会超过循环次数本身（实测 14 > 8）——**这种「不自洽的数」是最硬的证据**。
 *
 * ⚠ **不加 `__stdcall` 声明是刻意的**：加了就绕开了（前端走 stdcall 路径不加
 * 调用方清栈），而 `scripts/maui-vml-verify/corpus/c/skel.c` 的头注释里记的
 * 正是这个变通。那个变通只对「记得写声明」的调用方有效 —— 对 22 种语言前端、
 * 对任何没读到那份头的程序都不成立。**统一之后，写不写声明都必须是对的。**
 * 对照版本见 p4。
 *
 * 判据：数组 8 个元素逐个对，且循环次数与失配计数都自洽。
 */
int main(void) {
    int a[8];
    int i;
    int bad;

    a[0] = 1; a[1] = 2; a[2] = 3; a[3] = 4;
    a[4] = 5; a[5] = 6; a[6] = 7; a[7] = 8;
    bad = 0;

    /* 8 次库调用。约定一致时 SP 每次归位；不一致时每次 +4，累计 32 字节。 */
    println_int(0); println_int(0); println_int(0); println_int(0);
    println_int(0); println_int(0); println_int(0); println_int(0);

    for (i = 0; i < 8; i = i + 1) {
        if (a[i] != i + 1) bad = bad + 1;
    }

    if (bad != 0) {
        print_str("ABI-FAIL 局部数组被栈漂移踩坏，失配 ");
        println_int(bad);
        print_str(" 个（应 <= 8，超过说明连循环变量都被踩了）\n");
        for (;;) { }
    }
    print_str("ABI-OK\n");
    return 0;
}
