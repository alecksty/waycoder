/* host_probe.c —— **桌面宿主（scripts/vmlcli）的 syscall 探针**。
 *
 * ## 判据是"宿主给了程序什么"，不是"看起来对不对"
 *
 * 全部结果用 `ui_beep(频率)` 报出来：`ui_beep` 在桌面宿主上落成一行
 * `[vml-audio] tone hz=…`（见 `CliVmlHost.Tone`）。于是**一句话就能断言**
 * "程序收到的那个值是不是宿主该给的那个" —— 不靠截图、不靠时序、不靠肉眼看日志。
 *
 * 这套办法是被本仓自己的教训逼出来的（`docs/VML宿主接口.md` §8）：
 * 拿 `puts` 的输出当判据会被 stdio 的毛病带偏（同一个字符串打出两种结果，
 * 于是把 stdio 的问题看成了 codegen 的问题）；换成"宿主原样打印"之后，
 * 六个格子一次就量清了。**凡是"猜编译器/猜宿主"的结论，先在判定链上把 stdio 摘出去。**
 *
 * ## 频率编码
 *
 *   10xxx 屏幕：10320=SCR_W  10240=SCR_H  10001=方向（320>240 ⇒ 横屏，判定规则只有
 *               VmlUi.OrientationOf 一处实现）
 *   10xxx 存档：9999=没有的键（-1）
 *   11xxx 存档：11002=读回来的字节数
 *   12xxx 存档：12104=首字节 'h'
 *   15xxx 对话框：15001=消息框返回 1（= 否/取消）
 *   16xxx 对话框：16006=输入框写入 6 字节（"你好"）
 *   1xxx  消息类型（1001=KEYDOWN 1002=KEYUP 1009=TIMER 1011=WINDOWRESIZE 1012=WINDOWORIENT）
 *   4xxx  消息 A 槽（4037=左方向键  4013=回车）
 *   2xxx  消息 A 槽的另一支（2037）
 *   3007  定时器用户标记
 *   5xxx / 6xxx 窗口尺寸消息的新宽/新高（5800 / 6600）
 *   7001  方向消息（1 = 横屏）
 *   17xxx 定时器 id（17001 = 本运行第一个定时器）
 *
 * ## 入口参数（由 `run.sh` 给）
 *
 *   --screen 320x240         → 10320 / 10240 / 10001（横屏）
 *   --answer cancel          → 15001
 *   --answer 你好            → 16006
 *   --input  events.txt      → keydown 37 / keyup 13 / resize 800x600 / orient 1 四条
 *
 * ⚠ 四条输入事件**都在 t=0 就投进队列**（不等程序走到那一步）——
 * 于是"程序读到哪一条"与"程序启动多快"无关，判据是确定的。
 */
#include <waycoder_ui.h>

int msg[4];
char tbuf[64];

int main(void)
{
    int t;

    ui_win_open("宿主探针", 320, 240);

    /* ── ① 屏幕：`--screen 320x240` ─────────────────────────────── */
    ui_beep(10000 + ui_scr_w(), 20);          /* 10320 */
    ui_beep(10000 + ui_scr_h(), 20);          /* 10240 */
    ui_beep(10000 + ui_orientation(), 20);    /* 10001 = 横屏（320 > 240） */

    /* ── ② 存档：写 → 读（长度）→ 读（内容）→ 读一个没有的键 ────── */
    ui_store_set("probe.k", "hi");
    ui_beep(11000 + ui_store_get("probe.k", tbuf, 64), 20);      /* 11002 */
    ui_beep(12000 + tbuf[0], 20);                               /* 12104 = 'h' */
    ui_beep(10000 + ui_store_get("probe.none", tbuf, 64), 20);   /* 9999 = -1 */

    /* ── ③ 对话框：答案来自 `--answer` 队列 ────────────────────── */
    ui_beep(15000 + ui_dlg_msg("探针", "按脚本回答", 0), 20);     /* 15001（cancel） */
    ui_beep(16000 + ui_dlg_input("探针", "说点什么", tbuf, 64), 20); /* 16006（"你好"） */

    /* ── ④ 输入：指针式与无指针式**两种读法都要能用** ────────────── */
    ui_beep(1000 + ui_wait(msg, 0), 20);      /* 1001 = KEYDOWN */
    ui_beep(4000 + msg[1], 20);               /* 4037 = 左方向键 */
    ui_beep(1000 + ui_wait_msg(0), 20);       /* 1002 = KEYUP */
    ui_beep(4000 + ui_msg_a(), 20);           /* 4013 = 回车 */

    /* 屏幕变了也是**消息**（不是让程序自己去猜）：先方向、后尺寸（见 VmlMsgType）。
       桌面没有转屏，这两条只能由 `--input` 脚本喂 —— 手机端由绘图页投递，走的是同一个队列。 */
    ui_beep(1000 + ui_wait(msg, 0), 20);      /* 1011 = WINDOWRESIZE */
    ui_beep(5000 + msg[1], 20);               /* 5800 = 新宽 */
    ui_beep(6000 + msg[2], 20);               /* 6600 = 新高 */
    ui_beep(1000 + ui_wait(msg, 0), 20);      /* 1012 = WINDOWORIENT */
    ui_beep(7000 + msg[1], 20);               /* 7001 = 横屏 */

    /* ── ⑤ 定时器：装一个 60ms 的，等它自己来 ───────────────────── */
    ui_beep(17000 + ui_timer_set(60, 7), 20); /* 17001 = 第一个定时器 id */
    t = ui_wait(msg, 2000);
    ui_beep(1000 + t, 20);                    /* 1009 = TIMER */
    ui_beep(2000 + msg[1], 20);               /* 2001 = 定时器 id */
    ui_beep(3000 + msg[2], 20);               /* 3007 = 用户标记 */

    return 0;   /* 直接收工 —— 不依赖"关窗"，免得把输入与退出耦在一起 */
}
