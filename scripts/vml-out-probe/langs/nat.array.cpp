// nat.array.cpp —— **C++ 前端的数组专项探针**。
//
// ## 为什么单独立一条（而不是并进 nat.cpp）
//
// 实测 C++ 前端的**数组元素读取是坏的**：`g[i]` 编出来「取数组的值而不是地址、
// 多算一个 +4、最后根本不解引用」，读到的永远是垃圾（实测恒为 0）。
// 而 `nat.cpp` 那三行只打**字面量**，一个数组都不碰 ⇒ 这条链坏了很久，
// 跨语言输出探针一直是绿的，什么都没照出来。
//
// 这与本仓反复出现的形态同源：**探针太窄，窄到下不了结论**。
//
// ## 判据挑的三种形态
//
//   ① **全局数组 + 常量下标**（`g[0]`、`g[3]`）—— 最基础的那条路；
//   ② **全局数组 + 变量下标**（循环里 `g[i]`）—— 下标不是字面量时另走一条；
//   ③ **局部数组**（`loc[0]`）—— 另一套寻址（栈帧 vs 数据段）；
//   ④ 外加**写回**（`g[1] = 99`）与 file-scope `static`。
//
// ⚠ 期望值配在 `nat.array.cpp.expect`（专项探针自带期望，默认那三行 OUT-* 不适用）。
//
// ⚠ **KNOWN-RED（2026-09-22）**：这条判据立起来的时候**是红的**，而且是有意入的。
//   现状（v0.96.380 实测）：
//
//       A-G0=0 / A-G3=0 / A-GSUM=0 / A-G1W=99 / A-LOC=0 / A-S2=0
//
//   注意 `A-G1W=99` 是**通的** —— 写和读用的是**同一个错误地址**，所以写回自洽。
//   这恰好说明坏的是"地址怎么算"，不是"读写两条路各坏各的"。
//
//   已定位到两处（都在 C++ 的 `[]` 代码生成里，`CodeGenerator.Expressions.cs` 的 `case "[]"`）：
//     ① **基址取的是值不是地址**：C 生成 `move @R0 g`，C++ 生成 `move @R0 [var_g]`；
//     ② **多算一个 +4**（`hasHeader` 分支），而数据段里根本没有那个头。
//   另有 `(Rn)` 形态的 `Mem()` 简写（`CodeGenerator.cs` 的 `AddOp`）只覆盖 R0–R3，
//   走到别的寄存器时会落进"含括号 ⇒ 当 MEMORY 字符串"的兜底分支。
//
//   修好之后这条会**自己变绿**，那时请把这三行 KNOWN-RED 说明一并删掉。
// KNOWN-RED
int g[4] = { 10, 20, 30, 40 };
static int s[3] = { 7, 8, 9 };

int main() {
    printf("A-G0=%d\n", g[0]);
    printf("A-G3=%d\n", g[3]);

    int sum = 0;
    for (int i = 0; i < 4; i++) sum += g[i];
    printf("A-GSUM=%d\n", sum);

    g[1] = 99;
    printf("A-G1W=%d\n", g[1]);

    int loc[3] = { 1, 2, 3 };
    printf("A-LOC=%d\n", loc[0] + loc[1] + loc[2]);

    printf("A-S2=%d\n", s[2]);
    return 0;
}
