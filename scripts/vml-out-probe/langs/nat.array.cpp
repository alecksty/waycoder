// nat.array.cpp —— **C++ 前端的数组专项探针**。
//
// ## 为什么单独立一条（而不是并进 nat.cpp）
//
// 实测 C++ 前端的**数组元素读取是坏的**：`g[i]` 编出来「取数组的值而不是地址、
// 多算一个 +4、最后根本不解引用」，读到的永远是垃圾（实测恒为 0）。
// 而 `nat.cpp` 那三行只打**字面量**，一个数组都不碰 ⇒ 这条链坏了很久，
// 跨语言输出探针一直是绿的，什么都没照出来。
//
// 这与本仓反复出现的形态同源：**探针太窄，窄到下不了结论**。
//
// ## 判据挑的三种形态
//
//   ① **全局数组 + 常量下标**（`g[0]`、`g[3]`）—— 最基础的那条路；
//   ② **全局数组 + 变量下标**（循环里 `g[i]`）—— 下标不是字面量时另走一条；
//   ③ **局部数组**（`loc[0]`）—— 另一套寻址（栈帧 vs 数据段）；
//   ④ 外加**写回**（`g[1] = 99`）与 file-scope `static`。
//
// ⚠ 期望值配在 `nat.array.cpp.expect`（专项探针自带期望，默认那三行 OUT-* 不适用）。
//
// ## 立这条判据时它是红的，现在绿了（修了什么）
//
// 立判据时的形态（v0.96.380 实测）：`A-G0=0 / A-G3=0 / A-GSUM=0 / A-LOC=0`，
// 而 `A-G1W=99` 是**通的** —— 写和读用的是**同一个错误地址**，所以写回自洽，
// 这恰好说明坏的是"地址怎么算"而不是"读写各坏各的"。
//
// 修了三处（都在 C++ 前端，两处活路径 + 一处字面量词法）：
//  ① **全局数组没有登记**：`_isArrayVar` 是**局部**变量的表，每进一个函数就被清，
//     表达式路径只看它 ⇒ 全局数组被当成标量，`g` 取到的是**值**不是地址。
//     加了独立的 `_globalArrays`；
//  ② **局部数组的基址取的是内容不是地址**：编出 `move @R0 [var_a]`（取到长度头 3），
//     再 `+4` = 地址 7 ⇒ 元素全写到地址 7 上。改成用 LABEL 操作数取地址；
//  ③ **十六进制字面量**：`val.EndsWith("F")` 让 `0xFFFFFF` 变成 FloatLiteral，
//     而躲过那条的（如 `0x000000`）会被 `int.TryParse("0x…")` 判失败、**静默变 0**。
//     BGI 的调色板全是十六进制 ⇒ 老图形程序画面全黑。
int g[4] = { 10, 20, 30, 40 };
static int s[3] = { 7, 8, 9 };

int main() {
    printf("A-G0=%d\n", g[0]);
    printf("A-G3=%d\n", g[3]);

    int sum = 0;
    for (int i = 0; i < 4; i++) sum += g[i];
    printf("A-GSUM=%d\n", sum);

    g[1] = 99;
    printf("A-G1W=%d\n", g[1]);

    int loc[3] = { 1, 2, 3 };
    printf("A-LOC=%d\n", loc[0] + loc[1] + loc[2]);

    printf("A-S2=%d\n", s[2]);
    return 0;
}
