// **`char`/`short` 数组：数据段按 4 字节存、下标按元素真实宽度走 —— 两边不一致**
//
// ✅ **已修（v0.96.370）**。修法：给数据段加 **1/2 字节的数组宽度**——
// C 前端按 `ArrayElemSize` 产出 `byte[]`/`short[]` → 文本层发 `.byte`/`.halfword` →
// 汇编器按指令名折成对应宽度的数组 → VMB 用新 tag `0x41`/`0x42` 走紧凑载荷 →
// 装载侧按真实宽度分配与铺字节。**宽度真源只有 `ArrayElemSize` 一处**，
// 存储与下标共用它（原先两处各算一遍，才是这个 bug 的根）。
//
// ## 症状
//
// ```c
// static char  one[3] = {1, 2, 3};   one[1]  →  0（应 2）
// static short tw[3]  = {1, 2, 3};   tw[1]   →  0（应 2）
// const  char  oc[3][3] = {{1,2,3},{4,5,6},{7,8,9}};   oc[1][0] → 0（应 4）
// ```
//
// ## 根因：数据段的元素宽度是**写死的一个 `.word`**，而下标的步长按类型算
//
// 数据段对**每个**数组元素都发一个 `.word`（4 字节），与元素类型无关；
// 而 `GenerateArrayAddress` 末尾的步长取自 `GetTypeSizeFromString(元素类型)` ——
// `char` 是 1、`short` 是 2。两边只在 `int`（4）上重合，所以
// **`int`/`bool` 一直是对的，`char`/`short` 才露**：
// `oc[1][0]` 按 1 字节算到偏移 3，落在第一个 `.word` 的**第 4 个字节**上（那里是 0）。
//
// `sizeof` 倒是按真实宽度报的（`sizeof(char[3]) == 3`、`sizeof(short[3]) == 6`），
// ⇒ 分配尺寸与访问步长自相矛盾，**不是"故意按 4 字节模型"**。
//
// STDIN:
// EXPECT: O1=2|T1=2|C10=4|C22=9|S10=4|S22=9|I10=4|BSZ=300|B0=0|B15=15|B100=100|B295=39|B299=0|BOK=1
#include <stdio.h>

static char  one[3] = {1, 2, 3};
static short tw[3]  = {1, 2, 3};

const char  oc[3][3] = {{1, 2, 3}, {4, 5, 6}, {7, 8, 9}};
const short os[3][3] = {{1, 2, 3}, {4, 5, 6}, {7, 8, 9}};

/* 对照：`int` 的步长恰好是 4，与数据段重合 ⇒ 一直是好的 */
