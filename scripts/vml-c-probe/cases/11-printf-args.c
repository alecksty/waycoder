// 变参**按显式数组**交给库函数之后，这条链上的判据
//
// 直接动因（用户定的硬规矩「自接读写地址的代码不要」）：`printf` / `sprintf` 原先用
// `int *stack_args = (int*)&fmt + 1;` **自己算形参地址**去取变参。那是猜栈布局：
// 既不是语言契约，也与形参个数耦合（`sprintf` 多一个 `buf` 形参就整体读偏过一次）。
// 已改成标准机制（`va_start` / `va_arg`，由前端内建实现）—— 变参先读进一个**显式的
// `int args[]` 数组**，再交给 `vsnprintf(buf, fmt, args, nargs)`。
//
// 这条用例压的是"换机制之后**没有读偏**"，因为读偏的症状是**静默的**：
// 把整数当指针解引用、或把字符串指针当整数打出来，都不会报错。
#include <stdio.h>
#include <string.h>

int main()
{
    char buf[32];
    int n;

    // ① 混合类型：错位一格就必然在这里露出来（整数当指针 / 指针当整数）
    printf("A=%s|%d|%c|%s\n", "s", 42, 'Z', "t");

    // ② 连续三个数字转换
    printf("B=%d-%d-%d\n", 1, 2, 3);

    // ③ `%%` **不消耗实参** —— 数转换符的那份判据（`format_arg_count`）要认这条，
    //    数多了会去读一个不存在的实参
    printf("C=100%%\n");

    // ④ `snprintf`：此前**只有声明没有实现**（一用就链不上）。
    //    判据同时看两件事：截断后的内容、以及**一定以 NUL 结尾**
    n = snprintf(buf, 5, "%s", "abcdefg");
    printf("D=[%s]|%d\n", buf, n);

    // ⑤ 装得下时原样（且结尾符不能少 —— 少了会带出缓冲区残渣）
    strcpy(buf, "zzzzzzzz");
    snprintf(buf, 32, "%d/%s", 7, "xy");
    printf("E=[%s]\n", buf);

    return 0;
}
// EXPECT: A=s|42|Z|t|B=1-2-3|C=100%|D=[abcd]|7|E=[7/xy]
//
// ⚠ `sscanf` 本条**测不了** —— 它是另一个独立缺陷（**本次新发现**，全仓此前对
//   `sscanf` **零覆盖**）：一个变量都不写回。已单列为 `12-sscanf.c`。
//   两条分开的理由：`printf` 家族五条全对、而它们与 `sscanf` **共用同一条
//   "数转换符"的判据**（`format_arg_count`）—— 混在一起会让"变参改走 va_list 做对了"
//   这条判据被一个陈旧缺陷染红，从而失去回归保护。
