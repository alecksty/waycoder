// **C 前端缺陷**：`char **` 的双下标 `p[i][j]` / 双重解引用 `**p` 取到的是 4 字节。
//
// ## KNOWN-RED —— 这是缺陷，不是"期望值写错了"
//
// 钉住它是因为**症状极其隐蔽**：编译全绿、运行不报错、`%s` 打印还"看着对"
// （`%s` 走的是地址、不经过元素类型推断），只有拿 `%d`/`%c` 把**字符当成数**读出来
// 才会露馅。而它砸掉的是一整类写法：
//
//   · `int main(int argc, char **argv)` —— 老程序的入口
//   · `getopt(argc, argv, "ab:c")` —— POSIX 命令行解析（见 `22-getopt.c`）
//   · `nyan_show(char **frames)` —— 本探针套件诞生的那个案例
//   · 任何"字符串表"（`char *names[]` + `names[i][0]`）
//
// ## 最小复现与判据
//
// ```
//   char *arr[2];  arr[0] = "AB";
//   printf("%d", arr[0][0]);      // 应 65 —— 实得 167789121（4 字节读）
//   printf("%d", (arr[0])[0]);    // 应 65 —— **实得 65**（加一层括号就对）
// ```
//
// **"加括号就对"是这条判据的关键**：说明问题出在**语法形态**（`a[i][j]` 这个
// 下标链怎么被解析/推断），不是"运行期读到脏内存"—— 后者不会因为多一对括号而改变。
//
// ## 已经查到哪一步 / 下一步从哪接
//
// 读 `VMLPrepares/CCompiler/` 的位置（**只读、未改动**）：
//
//   · 第 1 个下标 `p[i]` 单独取出来是**对的**（`q = p[i]; q[0]` ⇒ 65），
//     第 2 个下标 `p[i][j]`、以及 `**p` 才错 ⇒ 问题在**"下标作用于一个本身已经是
//     下标/解引用的表达式"**这条路径上，且内层的类型（`char*`，元素宽 1）没有被传下去
//   · 元素宽度退化成 4 ⇒ 与 CLAUDE.md ⑥「全局 `char` 数组下标读成 32 位」同一族
//     （`InferExpressionType(ArrayAccess)` 查不到就退回 `ExprType.Int`），
//     但这里的 base 是**指针而不是数组**，所以那次的补丁没覆盖到这条
//   · 下一步：在 `CodeGenerator.Expressions.cs` 的 `ArrayAccess` 分支上打一条
//     "推断出来的元素类型是什么"的日志，跑本用例的第 ①/②/③ 行对照即可定位。
//
// ⚠ **不要**为了让本用例变绿而把 `p[i][j]` 改写成 `(p[i])[j]` —— 那正是老程序
//   源码里的写法，绕过它就等于不测了。
#include <stdio.h>

/* 形参形状（`getopt` 就是这个签名）—— 与局部变量分开测，两条路都要错 */
int peek(char **av, int i)
{
    return av[i][0];
}

int main()
{
    char  *arr[2];
    char **pp;
    char  *q;

    arr[0] = "AB";
    arr[1] = "CD";
    pp = arr;

    /* ① 对照：先把 `p[i]` 取到标量再下标 —— 一直是**对的**，证明用例本身不空 */
    q = pp[0];
    printf("\nA=%d", q[0]);

    /* ② 缺陷：不加括号的双下标 */
    printf("\nB=%d", pp[0][0]);
    printf("\nC=%d", pp[0][1]);

    /* ③ 缺陷：双重解引用 */
    printf("\nD=%d", **pp);

    /* ④ 对照：加一层括号就**对了** —— 这条是"问题在语法形态"的判据 */
    printf("\nE=%d", (pp[0])[0]);

    /* ⑤ 形参形状（getopt 走的就是这条） */
    printf("\nF=%d", peek(arr, 0));
    printf("\nG=%d", peek(arr, 1));

    return 0;
}
// KNOWN-RED
// EXPECT: A=65|B=65|C=66|D=65|E=65|F=65|G=67
