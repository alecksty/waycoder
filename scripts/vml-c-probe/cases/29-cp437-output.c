// **DOS 程序的框线字节要能到达屏幕** —— 输出侧的编码判定。
//
// ## 症状：框线全变 `�`，而且**字节数对不上**
//
// 老程序（DOS/Turbo C 时代）画框线写的是**裸字节**：`0xC4`=`─`、`0xDA`=`┌`、`0xB3`=`│`。
// 它们**不是 UTF-8**，却正好落在 UTF-8 的**首字节区间**（`0xC0`–`0xDF` 两字节、
// `0xE0`–`0xEF` 三字节）⇒ 解码器把**后面那个字节**当成续字节一起吃掉，
// 两个字节换一个 U+FFFD。实测 `putchar(0xC4)` ×3 输出 `EF BF BD` ×3 ——
// 画面上是三个 `�`，**而占位都不对**，整幅图错位。
//
// ## 修法的判据：**先验后吃；验不过就认定整个程序是单字节老编码（粘性）**
//
// 「这一个字节走 CP437、下一个再试 UTF-8」是**不够**的 —— CP437 里存在
// **合法的 UTF-8 子串**，逐字节试会**在框线中间翻车**。最典型的就是本用例第一条：
//
//     `┌───┐` = `DA C4 C4 C4 BF`
//         DA C4 → 不合法 ⇒ `┌` ✓
//         C4 C4 → 不合法 ⇒ `─` ✓
//         C4 BF → **合法 UTF-8**（U+013F `Ŀ`）⇒ 吐出一个 `Ŀ` ✗
//
// 双线框更糟：`╔══╗` = `C9 CD CD BB`，`CD BB` 同样是合法 UTF-8。
// **光看字节流分不开** —— 这是信息层面的歧义，只能靠"这个程序整体是哪一种"来定。
// 判据取「**第一个不合法字节**」，粘住不再改。
//
// ## ⚠ 代价（有意接受）：一个程序只能是一种编码
//
// 粘性判定的意思是：**同一次运行里，一旦出现不合法字节，后面所有高位字节都按单字节解**。
// 所以"写中文 + 画 CP437 框线"的**混写程序**在这里是画不出来的 ——
// 但那种程序实际上不存在（要么是 UTF-8 的、要么是 DOS 时代的），
// 而**框线画不出来**是老程序兼容线上真实存在的那一类。
//
// ⚠ **UTF-8 那一侧不归本用例管**（本程序一旦画框就整体进单字节模式了）——
//   `20-curses-api.c` 的 `V=0,4` 那条的 refresh 输出里带着 `A中`，
//   它绿着就说明中文那条路没被这次改动碰到。**两条判据缺一不可**。
#include <stdio.h>

int main()
{
    /* ① 单线框 —— `C4 BF` 那一对就是"合法 UTF-8 子串"的判据 */
    printf("\nB1=");
    putchar(0xDA); putchar(0xC4); putchar(0xC4); putchar(0xC4); putchar(0xBF);   /* ┌───┐ */

    /* ② 双线框 —— `CD BB` 同上 */
    printf("\nB2=");
    putchar(0xC9); putchar(0xCD); putchar(0xCD); putchar(0xBB);                  /* ╔══╗ */

    /* ③ 竖线夹 ASCII —— 高位字节**不能吃掉后面那个字节**（这是原症状的指纹：
          吃掉的话 `x` 会消失，或者 `│x│` 变成一个 U+FFFD） */
    printf("\nB3=");
    putchar(0xB3); putchar('x'); putchar(0xB3);                                  /* │x│ */

    /* ④ 块字符 + 希腊字母（CP437 的另外两段，顺带压查表的下标）
          0xB0 ░ / 0xDB █ / 0xE3 π / 0xF6 ÷ */
    printf("\nB4=");
    putchar(0xB0); putchar(0xDB); putchar(0xE3); putchar(0xF6);                  /* ░█π÷ */

    /* ⑤ ASCII 不受影响（单字节模式下 `b < 0x80` 原样返回） */
    printf("\nA=%d", 42);
    printf("\n");

    return 0;
}
// EXPECT: B1=┌───┐|B2=╔══╗|B3=│x│|B4=░█π÷|A=42
