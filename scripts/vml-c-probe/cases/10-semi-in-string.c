// 字符串字面量里的 `;` 被当成语句分隔符 —— 字面量在那里**被截断**，还多吐一个 `"`
//
// 影响面极大：**ANSI 转义序列全是分号分隔的**（`\x1b[1;31m`、`\x1b[38;5;208m`、
// `\x1b[48;2;60;0;90m`…）⇒ 凡是用带参数的颜色/样式序列的程序，输出都会缺一段。
// 一般字符串里带 `;` 的（SQL、路径列表、`k=v;` 那种）同样中招。
//
// 发现经过：写终端行为探针（`Examples/c/tty_legacy.c`）时，屏幕上出现
// `"5] 256-color` / `"[38[6] wide` 这种残缺 —— 一开始以为是命令行页的渲染问题，
// 把**程序自己的字节**打出来一比才发现乱码是程序产出的（本仓那条老规矩：
// 先分清"是它算错了还是我渲染错了"）。
//
// 隔离出来的边界很清楚：
//   · `puts("Q1;X")`      → `"Q1`     ❌ 截断且多引号
//   · `printf("P1;X\n")`  → `"P1`     ❌ 同上
//   · `printf("P2\tY\n")` → `P2<TAB>Y` ✅ 没有 `;` 就正常
// ⇒ 触发条件是**字面量里的 `;`**，与 `printf`/`puts`、与 `\x1b` 都无关。
//
// **绕法**：查表拼串——把带 `;` 的转义拆成两段不含 `;` 的片段再拼，
// 或者干脆用 `\x1b[38;5;208m` 之外的写法（如 16 色命名序列 `\x1b[91m`，它不带分号）。
#include <stdio.h>

int main()
{
    puts("K1=A;X");
    puts("K2=B-no-semi");
    printf("K3=C;Y\n");
    puts("K4=done");
    puts("K5=http://x/y");   /* `//` 同理：两条注释规则都必须是引号感知的 */
    return 0;
}
