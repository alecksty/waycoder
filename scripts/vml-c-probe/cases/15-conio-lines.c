// conio 的**行操作**判据：`clreol` / `delline` / `insline` / 滚屏。
//
// ## 为什么单独一条
//
// 这四个是 conio 里**实现最绕**的地方：本平台的字符网格**不支持** ANSI 的 DL/IL
// （`ESC[M` / `ESC[L`），所以 `conio.c` 自己留了一份**屏幕影子**，改完把受影响的
// 行**整行重发一遍**。"重发"这件事**没有别的观测手段** —— 搬错了只会在屏幕上留错行，
// 不报错、也不影响任何返回值（顺带：`clreol`/`delline`/`insline` 全是 `void`，
// 返回值这条路本来也走不通）。
//
// ## 为什么期望串那么长（**不是判据写松了**）
//
// 重发走 `con_redraw_range`：整行**固定 80 格**，属性一致时只发一次定位 + 一次 SGR。
// 所以期望 = `\e[行;1H` + `\e[37m\e[40m` + 80 个字符（大多空格）。这就是命令行页
// 实际渲染的那些字节，是**真契约**。
//
// 让判据行**不以空格结尾**：`delline`/`insline` 收尾会 `con_cup` 把光标放回原处，
// 所以期望串末尾是 `\e[24;1H`（尾部空格在编辑器/工具里容易被吃掉，判据会莫名变红）。
//
// ## 两条排布上的讲究
//
// · **`gotoxy` 与判据 `printf` 的先后**：`gotoxy` 发的 `ESC[行;列H` 属于"当前判据行"，
//   所以本组要移动光标时，`printf("\nKEY=")` 得写在前面（详见 14-conio-color.c）。
// · **滚屏（H 组）会重发整屏**（25 行 × 80 格，两千多字符），不能塞进判据行里。
//   办法是先 `printf("\n")` 把上一条判据封口、让那一大坨独占一段**行首不是 `KEY=`**
//   因而被 run.sh 的行首锚定忽略掉的行。
//
// ⚠ F / G 是**连锁**的：G 复用 F 之后的屏幕（Z 停在第 24 行）。F 错了 G 也会错，
//   查的时候先看 F。
#include <stdio.h>
#include <conio.h>

int main()
{
    clrscr();

    /* E：`clreol` 只发「定位 + 擦到行尾」，**不重发**已经画过的内容。
       （两次 `ESC[3;5H`：一次是 `gotoxy` 的、一次是 `clreol` 自己收口的。） */
    printf("\nE=");
    gotoxy(5, 3);
    clreol();

    /* `clreol` **不推进光标** —— 老程序拿它"擦掉这一行剩下的"之后接着写，位置得还在原处 */
    printf("\nE2=%d,%d", wherex(), wherey());

    /* F：`delline` —— 删掉光标所在行，**下面的上移**（末行的 Z 顶掉第 24 行） */
    printf("\nF=");
    gotoxy(1, 25);
    cputs("Z");
    gotoxy(1, 24);
    delline();

    /* G：`insline` —— 在光标行插入一空行，**下面的下移**（Z 被挤到末行、原处变空） */
    printf("\nG=");
    gotoxy(1, 24);
    insline();

    /* H：滚屏 —— 末行再换行，光标**钳在最后一行**（DOS 语义不是回绕到第 1 行）。
       滚屏那一大坨单独占一段（见文件头说明），不污染判据行。 */
    printf("\n");
    gotoxy(1, 25);
    putch(10);
    printf("\nH=%d,%d", wherex(), wherey());

    return 0;
}
