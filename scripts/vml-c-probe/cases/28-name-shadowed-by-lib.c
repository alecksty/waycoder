// **用户定义的同名函数被库函数静默劫持** —— 已知缺陷，**未修**。
//
// ## 症状：函数体汇编逐字正确，调用点却打不出东西
//
// 本用例的 `peek` 与 `builtins` 库里那个（`int peek(int addr)`，读内存）**同名**。
// C 的语义很清楚：**本翻译单元里的定义遮蔽库符号** ⇒ `peek(0)` 该进用户那个。
// 实际却是 `call lib_builtins_peek` —— 用户那个函数**从头到尾没有任何人调用**。
//
// 症状之所以难查，是因为**函数体本身完全正确**：
// `--vml` 打出来一看，`peek:` 那段汇编一字不差、参数读取（`[@R12+12]`）也对，
// 于是会一路怀疑类型推断、参数传递、寄存器分配……
// **而调用根本没进去。** 只有把函数改个名字（`mypeek`）才会好 ——
// 那正是掩盖问题，不是修它。（实测：`cases/23` 的 F/G 两条就是这么红了一轮。）
//
// ## 为什么难修（试过一版，撤回了）
//
// 判据似乎该是「主程序自己定义了这个标签就不许改写」，但
// `VmlProgram.Labels` **不是可靠的真源**：
//   · 它只有十几个条目、地址还是**前端留下的陈旧占位**
//     （实测 `peek = 0`，和一堆字符串标签挤在地址 0 上）
//   · 指令的 `Label` 字段也是空的
// 而按「同名就保护」一刀切会**打断 native 声明**：JS 前端的
// `native function println_str(s) {}` 走的是 `AddLabel(name)` 之后直接 `return`
// ⇒ 留下一个**空标签**，本来就该让库接管。一刀切之后
// `call println_str` 不再被解析到 `lib_io_println_str`，
// 整个 JavaScript 的输出全废（崩在 `PUSH @R0`，SP=FFFFFFFC，一个字都没打出来）。
//
// **所以这条要修，得先有一个"这个标签是不是真定义"的可信判据** ——
// 目前 `Lib/` 侧没有。别在链接器里按形状猜。
//
// 名字冲突在老程序里并不罕见（`index`/`time`/`remove`/`getline`/`peek`…），
// 而且**是静默的**，所以值得留一条判据在这里。
#include <stdio.h>

/* 用户自己的定义。返回值取一个库那边**不可能**给出的哨兵值。 */
static int peek(int x)
{
    return 12345 + x;
}

int main()
{
    printf("\nA=%d", peek(0));      /* 应 12345（用户那个） */
    printf("\nB=%d", peek(7));      /* 应 12352 */
    printf("\n");
    return 0;
}
// KNOWN-RED
// EXPECT: A=12345|B=12352
