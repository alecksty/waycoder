// 指向指针的指针：`char **` 形参 / 全局 / 字符串数组
//
// 直接动因：移植 nyancat 时 `nyan_show(char ** fr)` **编译全绿、运行不报错，
// 但取到的全是空**（3 帧只发出 3 个 ESC，每帧一个复位）—— 帧数据的着色字符一个没读到。
// 单独测下来是"形参里的 `char **` 拿不到基指针"（顶层下标是好的，一进函数就丢）。
//
// 这条对 curses 库是**要害**：ncurses 内部全是 `WINDOW *`（结构体指针），
// 而它的公开 API 又大量传 `char **`（菜单项、行缓冲）。这一条不通，库就得整体绕开指针。
#include <stdio.h>

char * rows[] = { "abc", "def" };

char ** g_rows;

char at2(char ** r, int i, int j)
{
    return r[i][j];
}

char * pick(char ** r, int i)
{
    return r[i];
}

int main()
{
    printf("Q1=%s\n", rows[0]);
    printf("Q2=%c\n", rows[1][1]);
    g_rows = rows;
    printf("Q3=%s\n", g_rows[1]);
    printf("Q4=%c\n", at2(rows, 0, 2));
    printf("Q5=%s\n", pick(rows, 1));
    return 0;
}
// KNOWN-RED: 多级指针的**下标展平**（`rows[1][1]`、`g_rows[1]`、经形参的 `r[i][j]`）
// EXPECT: Q1=abc|Q2=e|Q3=def|Q4=c|Q5=def
//
// ── 已修（v0.96.336）：`Q1` 从 `(null)` 变 `abc`，真因是**三处独立缺陷**叠加 ──
//   ⚠ 本文件原先写的「形参里的 `char **` 拿不到基指针（顶层与全局下标正常，一进函数就丢）」
//     **是错的** —— 顶层与全局当时也是坏的，而且坏在三处、与"是不是形参"无关。
//   ① `VmlProgram.RemoveUnusedData` 只从**指令**的操作数收集"用到的标签"，然后删掉其余数据项。
//      而指针表里的字符串**只被别的数据项引用**（`.word L_x`），指令里一次都不出现
//      ⇒ **整条被删**，运行期读到不存在的标签。已补"数据段内部引用"的传递闭包。
//   ② `FlattenArrayInitializer`（及 static 局部的同源那份）把字符串**内容**直接塞进数组，
//      序列化成 `.word abc` —— 把内容当标签名写出去，而 `abc` 这个标签根本不存在。
//      已改成"给字符串分配数据段标签、数组元素存标签名"。
//   ③ `char *rows[]` 的元素类型被判成 `char`（`StringToExprType` 先把 `[]` 剥掉再看 `*`），
//      于是下标按**字节**读写（`moveb`+`sextb`）—— 读指针只读到地址的最低一个字节。
//      已按「声明的 `*` 在 `[` 之前 ⇒ 元素就是那个指针」修正（类型推断与步长两处同源判据）。
//
// ── 仍未修：**多级下标被展平成一个偏移** ──
//   `rows[1][1]` 生成的是 `*(rows + (1+1)*4)` —— 两个下标**先相加**、再乘一次步长。
//   对真正的矩形数组（`int a[3][4]`）该是 `(i*4 + j)*size`；而对 `char *rows[]`
//   更是根本性的错：**第二个下标作用在另一个对象上**（`rows[1]` 那个指针指向的串），
//   与 `rows` 的偏移毫无关系。`char **p` 的 `p[1]` 同理（元素是 `char *`，步长该是 4 而不是 1）。
//   修法方向：判据收成**一份**「元素类型是不是指针」，
//   是指针时**不展平**（先 `*(base + i*4)` 取出指针，再对它做第二个下标）。
