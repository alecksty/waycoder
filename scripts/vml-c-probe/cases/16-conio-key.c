// conio 的**键盘**判据：`getch` / `getche` / `kbhit`。
//
// ## 为什么单独一条
//
// 这三个是**唯一**要读 stdin 的 conio 接口，而它们此前一条判据都没有 ——
// 因为桌面脚手架根本喂不进输入（见下）。而"按键收不到"正是游戏类老程序
// 最要命的故障（方向键不响应 = 玩不了），且**完全不报错**。
//
// ## 判据的两半：喂进去 + 读出来
//
// · **喂**：`// STDIN: wsad`（run.sh 认这行，转成 `vmlcli --stdin`）。
//   语义与手机端逐条对齐 —— **一行 = 用户依次按下的那几个键**（见 vmlcli
//   `CaptureIo` 的注释）。
// · **读**：把每个按键的**编码值**打到 stdout 比对。不打印字符本身，是因为
//   字符会和 conio 画面混起来、肉眼分不出边界。
//
// ## 期望值的依据：DOS 的 `getch()` 是**一下按键一个字符**
//
// 敲 "wsad" = 按了 w、s、a、d 四个键 ⇒ 四次 `getch()` 就该依次拿到
// 119 / 115 / 97 / 100。**不能**只拿到第一个（那剩下的三个键就凭空消失了）。
//
// ## 怎么造出来的（记一笔，这是本用例存在的原因）
//
// 本用例写出来时先红在**一个更靠底层的缺陷**上：`getchar()` 恒返回 0/垃圾 ——
// C 前端里 `int c; asm("SYSCALL #5"); return c;` 这种写法**把 syscall 的返回值
// 整个丢掉**（正确写法是把 asm 当表达式：`return asm("SYSCALL #5");`，规则写在
// `Lib/shared/src/vmlui.c` 头部）。修掉 `io.c` 的 `getchar` 之后才轮到这里。
// ⇒ 顺带说明**为什么这个用例非有不可**：它压的是"输入这条路端到端通不通"，
//   而那条路上任何一层断了，症状都只是"程序没反应"。
#include <stdio.h>
#include <conio.h>

int main()
{
    /* 一行四个键 ⇒ 四次 getch 依次拿到 w/s/a/d（DOS 语义：一下按键一个字符）。
       ⚠ 只取到第一个、后面全丢，是本用例要钉死的那种"静默丢输入"。 */
    printf("\nK1=%d", getch());
    printf("\nK2=%d", getch());
    printf("\nK3=%d", getch());
    printf("\nK4=%d", getch());

    /* 键用完再取 ⇒ 空行 ⇒ DOS 里最常见的"回车确认"（13）。
       老程序 `ch = getch(); if (ch == 13) ...` 就是靠这条 */
    printf("\nK5=%d", getch());

    /* `kbhit()`：命令行页的 stdin 是**按行**交给程序的（敲一行、按运行才提交），
       所以"此刻有没有按键"**预知不了** —— 恒 0 是有意的（写在 conio.h 里）。
       钉住它，免得将来有人把它改成"看起来更聪明"却不可实现的东西。 */
    printf("\nHIT=%d", kbhit());

    return 0;
}
// STDIN: wsad
// EXPECT: K1=119|K2=115|K3=97|K4=100|K5=13|HIT=0
