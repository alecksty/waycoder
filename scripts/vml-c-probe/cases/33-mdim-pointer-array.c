// **二维指针数组的"元素"读成了一层引用之外的东西**（`char *tab[2][3]`）
//
// ## 症状
//
// `static char *bs[2][3] = {{"a1","a2","a3"},{"b1","b2","b3"}};` 读 `bs[0][0]`
// 得到 **97（`'a'`）** —— 那是字符串 `"a1"` 的第一个字节，不是那个指针；
// `%s` 打出来是**空串**。而**一维**的 `char *rows[]` 一直是对的。
//
// ## 根因：数组的下标**走维度**，只有指针的下标才**解引用**
//
// `InferExpressionType` 里那条"多级下标要按级数继续解引用"是照 `T **p` 写的。
// `char *bs[2][3]` 不是指针 —— 两级下标都在同一个二维数组上走维度
// （行优先展平 `base + (i*3 + j)*4`），元素类型始终是 `char *`。
// 照指针那条规则多解一层，`bs[i][j]` 就被判成 `char` ⇒ 末次取值按 1 字节读。
// 同时 `GenerateArrayAddress` 里那段"多级下标 + 元素是指针"的特判
// 也把二维数组当成了指针的指针 ⇒ 基址取成"元素里存的那个指针"、再多读一层
// （实测取出 `0x61003161`，正是 `"a1"` 的头四个字节 `a 1 \0 a`，随后内存错误）。
//
// 两处都已按"**下标数 − 数组维度数**"改成该解几层解几层
// （`DeclaredArrayDims` 是"维度数"的唯一判据）。
//
// ## 为什么它值钱
//
// 老程序的**字符串表**几乎都是二维的：`sl` 的整车图形（`d51[6][11]`）、菜单、
// 字模、`argv` 那类。修前 `sl` 的火车一个字符都画不出来。
//
// ⚠ 断言刻意只看**稳定量**（指针的字节距离、指向的字符、字符串本身）——
//   绝对地址随布局漂，不能进判据。
// ⚠ 另外两条**不**放进来（各自是独立的事，混压会让这条判据红在不相干的原因上）：
//   · `strlen(ds[0][0])` 恒为 0（把嵌套下标当实参传给带原型的函数）；
//   · 函数内 `static` 数组（含宏字符串表）整条路都坏 —— 见 `cases/34`。
// STDIN:
// EXPECT: INIT=6|W=3|CH=97|S=[a1]|B=[b1]
#include <stdio.h>

static char *bs[2][3] = {{"a1", "a2", "a3"}, {"b1", "b2", "b3"}};

int main()
{
    /* INIT：六个元素都读得到（相邻两个指针差 3 —— "a1"/"a2" 各占 3 字节含结尾 NUL） */
    printf("INIT=%d\n", ((int)bs[0][1] - (int)bs[0][0]) == 3 ? 6 : 0);
    /* W：元素步长 */
    printf("W=%d\n", (int)bs[0][1] - (int)bs[0][0]);
    /* CH：末次取值必须是**那个指针指向的字符**，不是指针自己 */
    printf("CH=%d\n", (int)bs[0][0][0]);
    /* 字符串本身（这一条最关键：多解一层会打成空串） */
    printf("S=[%s]\n", bs[0][0]);
    printf("B=[%s]\n", bs[1][0]);
    return 0;
}
