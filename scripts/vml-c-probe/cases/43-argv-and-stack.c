// **`main` 的 argc/argv + 栈不能长到堆里**（两处都是运行时入口的事，已修）
//
// 由来：`sl` 一开局就崩在 `for (i = 1; i < argc; ++i) if (*argv[i] == '-')`，
// 而 `argc` 读出来是 **897988541** —— 那是 0x358637BD，某个浮点常量 `1e-6` 的位模式。
//
// ## 缺陷 A：入口**没给 `main` 搭帧**（`argc`/`argv` 读到没写过的内存）
//
// C 的调用约定里 `call` 会把**返回地址**压栈、参数落在它**之上**，所以被调用方读参数的位置是
// `[R12+12]`（第一个）、`[R12+16]`（第二个）……（`main` 的序言 `push R15 / push R12 /
// move R12 R13` ⇒ R12 在初始 SP 之下 8 字节）。而运行时那段原来是
// `if (privilegeLevel == 0 && CommandLineArgs.Count > 0)`：
//   · `privilegeLevel` **默认是 1**（MCU 模式）⇒ **整段从来没执行过**；
//   · 就算执行，也只在**有参数时**才压，且**少压了返回地址槽**。
// ⇒ `main` 的 `[R12+12]` 落在**初始 SP 之上**、读到没写过的内存。
// 修法：无条件搭三格 —— **argv、argc、返回地址**（返回地址最后压、落在最低地址），
// `argc` 至少 1、`argv[0]` 一定可读（没有参数时给空串），返回地址给 **0**
// （`ExecuteRet` 把 `<= 0` 当"从入口返回"⇒ 结束程序、退出码取 R0 = `main` 正常 return 的语义）。
//
// ## 缺陷 B：**栈顶落在堆里面**（数据段一大就撞上）
//
// 栈从 `sp` 往下长、堆从 `DataBase` 往上长，而 `sp` 原来取自 `config.StackSize` = **64K**，
// 运行时**从不检查**堆有没有越过它。实测 `sl`：`heapTop=67342 > sp=65536`，
// 于是 `main` 的参数槽（`[R12+12]`=0x10004）正好落在**堆的数据**上 ——
// 缺陷 A 之所以表现为"读到某个浮点常量的位模式"，就是它读到了堆里的浮点常量。
// 修法：`if (sp <= memoryAllocPtr) sp = memory.Length - 4;`（退到内存顶端）。
//
//   ⚠ 单测 A 或单测 B 都测不出来：A 让参数槽指向"没写过的内存"（通常是 0，看着还挺对），
//     B 只有**数据段+堆超过 64K** 的程序才踩。所以这条用例**两样都要**：
//     既真的读 `argc`/`argv`（A），又带一块 70000 字节的数据（B）。
//
// ⚠ 断言 `ARGC=1` 是有意的：探针不给程序传参数 ⇒ `argc` 必须**恰好** 1。
//   修前它是随机的（几十亿），这条一比就红。
// STDIN:
// EXPECT: ARGC=1|A0=1|ANULL=1|BIG=1|LOOP=1
#include <stdio.h>

/* 让堆越过默认栈顶（64K）—— 缺陷 B 的触发条件。
   `char` 数组按 4 字节/元素开（既有行为），70000 项就是 280000 字节。 */
static char big[70000];

int main(int argc, char *argv[])
{
    int i, ok = 1;

    big[0] = 1;
    big[69999] = 7;

    printf("ARGC=%d\n", argc);
    printf("A0=%d\n", argv[0] != 0 ? 1 : 0);          /* C 保证 argv[0] 可读 */
    printf("ANULL=%d\n", argv[argc] == 0 ? 1 : 0);    /* C 保证 argv[argc] == NULL */
    printf("BIG=%d\n", big[69999] == 7 ? 1 : 0);      /* 数据段没被栈/其它写坏 */

    /* `sl` 出事那一句的形状：`argc` 是垃圾时这里会越界读 `argv[i]`。 */
    for (i = 1; i < argc; ++i)
        if (argv[i][0] == '-') ok = 0;
    printf("LOOP=%d\n", ok);

    return 0;
}
