// **函数内 `static` 数组**：三处独立缺陷（已全部修复，本用例把它们钉住）
//
// 由来：修好二维指针数组（`cases/33`）之后，`sl` 仍然画不出火车。插桩读数把范围收到
// **函数内 static 数组**这一条上 —— 而老程序里"函数内静态查表"（整车图形、字模、
// 菜单、CRC 表）几乎都是这个形状，所以这一档值得一条常驻判据。
//
// ## 缺陷 A：元素恒 NULL —— **装载侧的遍历序**
//
// `static char *stat[2] = {"sa","sb"};` 读 `stat[0]` 得 **0**（`%s` 打 `(null)`），
// 而非 static 的 `char *plain[2]` 是好的；数据段**是对的**（产物里 `f__stat: .word L_…` 两条）。
// 真因不在编译器而在**装载**：数据段是**按字典遍历序**逐个 `AllocateMemory` 并登记地址
// （`labelAddresses[key] = address` 在**循环末尾**），而 `object[]` 元素指向的标签
// （指针表里的字符串）完全可能排在**后面**才登记 ⇒ 边遍历边解析就读到 0。
// 单个 `LabelRef`（`T *p = &x;`）本来就有"延后补填"，**数组元素这条路没有** —— 补上即可。
// 指纹：**同一个形状，放函数里就坏、放顶层就好**（顶层那份恰好顺序凑巧）。
// 判据：`STATIC=1`、`SD=3`。
//
// ## 缺陷 B：维度写成表达式 ⇒ **初始化器整个丢掉**
//
//     static char *a[D51HEIGHT]      = {"sa","sb"};   /* 裸宏（预处理后是裸数字）：正常 */
//     static char *b[D51HEIGHT + 1]  = {"ma","mb"};   /* 宏 + 1 ：`probe__b: .word 0` */
//     static char *c[2 * 5]          = {"xa","xb"};   /* 表达式：同上 */
//
// 局部声明的维度判据**有两套**：`Parser.Expressions`（数组声明）用 `TryConstDim` 折常量，
// 而 `Parser.Statements`（局部声明）只把「**NUMBER 紧跟 `]`**」当编译期维度、其余全当 VLA ——
// 于是 `[H + 1]`、`[2 * 5]` 被判成运行时维度，顺着 VLA 那条路走下去，而
// `GenerateVariableDecl` 的 VLA 分支**第一句就 return**（"VLA 不支持初始化器"）
// ⇒ 初始化器整个被丢掉，数据段只剩预扫描留下的 `.word 0`：**编译不报错、元素全读到 0**。
// 同一个表达式写在**顶层**或**非 static 局部**上却正常，因为那两条路走的是唯一真源
// `TryConstDim` —— 「同一个表达式换个位置就坏」正是**两套判据**的指纹。
// 判据：`MACRO=1`、`EXPR=1`。
//
// ## 缺陷 C：产物文本里**只被别的数据引用**的东西被整批删掉
//
// 这条**只有 `EXPECT-VML` 那种"看产物"的断言抓得到**：死代码消除判"谁被引用"时只认
// **标签名字符串**，而文本往返一趟之后元素变成了 `LabelRef` ⇒ 指针表里的字符串被当
// "没人引用"删掉。症状极隐蔽：数据段里 `.word L_x` **照旧原样输出**，只是 `L_x` 退化成
// `.text` 里的一个**空标签**（看起来"数据都在"，只有内容是空的）。
// 用户侧后果：**手机「VML 编译」出来的 `.vml` 跑起来指针全 NULL**（那条路正是
// `ToString()` → 存盘 → 独立汇编运行）。
//
//   ⚠ 断言必须用**只有 static 表才有的字面量**（`"sa"`/`"ma"`/`"xa"`）：
//     非 static 的 `plain` 那两条字符串是被**指令**引用的（`MOVE R0 L_x` 后存栈），
//     死代码消除删不到它 —— 拿 `"aa"` 去断言，修前修后都是绿的，等于没测。
//
// ## 三条都是"编译全绿、跑起来才错"
//
// ⚠ 断言只看**分类值**（1 = 指针像个有效地址），不打 `%s` ——
//   `%s` 撞上 0 指针会把整个用例打崩、输出一片空白，
//   那时"已知红"与"程序挂了"就分不出来了。
// STDIN:
// EXPECT: PLAIN=[aa]|STATIC=1|SD=3|MACRO=1|EXPR=1
// EXPECT-VML: "sa"
#include <stdio.h>

/* ⚠ 用例必须**自包含**：原先这里写的是 `#include "sl.h"`，而那个头在 `.scratch/` 里
   （`sl` 的源码树）—— 于是这条用例**从来没编译过**，"实得"恒为空。
   而空结果在 runner 里与"值不对"一样算不匹配 ⇒ 它一直以"已知红"的样子躺着，
   **实际上什么都没量**（本仓记过的"判据装置自己骗人，比被测代码出错更难查"）。 */
#define D51HEIGHT 10

static void probe(void)
{
    char *plain[2] = {"aa", "bb"};                      /* 非 static（对照，一直正常） */
    static char *stat[2] = {"sa", "sb"};                /* 缺陷 A */
    static char *macro[D51HEIGHT] = {"ma", "mb"};       /* 缺陷 B（裸宏维度） */
    static char *expr[D51HEIGHT + 1] = {"xa", "xb"};    /* 缺陷 B（宏 + 常量表达式） */

    printf("PLAIN=[%s]\n", plain[0]);
    printf("STATIC=%d\n", (int)stat[0] > 100 ? 1 : 0);
    /* 两条都要解析出来（只测第 0 条的话，"两个元素指向同一处"也照样绿）——
       字符串 "sa" 连同结尾 NUL 占 3 字节，地址差就只能从字符串区的大小推。 */
    printf("SD=%d\n", (int)stat[1] - (int)stat[0]);
    printf("MACRO=%d\n", (int)macro[0] > 100 ? 1 : 0);
    printf("EXPR=%d\n", (int)expr[0] > 100 ? 1 : 0);
}

int main()
{
    probe();
    return 0;
}
