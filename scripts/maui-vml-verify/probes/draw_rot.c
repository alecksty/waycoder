/* draw_rot.c —— **画布变换的 A/B 对照用例**（静态画面，两次截屏可逐像素比对）。
 *
 * ## 它为什么必须存在
 *
 * 矢量后端有个优化：**刚体变换（纯旋转+平移）不逐点变换，而是把矩阵交给平台画布** ——
 * 这样矩形还是矩形、圆还是圆，能走平台原生图元（`DrawRect`/`DrawOval`），
 * 省掉"每个点一次平台路径构建"（真机实测差三个数量级）。
 *
 * 但这条路**写错了不会崩、不会报错，只会画得不对**（矩阵参数顺序错一位就是转置 ⇒
 * 镜像/错切）。而它的调用点又恰好是"每帧几千次"，慢一点快一点全在数字里，
 * 图形对不对反而没人看。
 *
 * 所以要有这么一张**静态**图：同一份几何，一半走刚体（画布变换）、一半走非刚体（逐点变换），
 * 两条路的输出摆在一起比对。
 *
 * ## 画面怎么读
 *
 * 图块是 100×60 的蓝底白框矩形：
 *   · 左上 (150,100) 原尺寸不转   → 100×60 的横矩形（**恒等，两次都一样**）
 *   · 左中 (150,300) 原尺寸转 90° → 应当变成 60×100 的**竖**矩形（刚体 ⇒ 画布变换）
 *   · 左下 (150,500) 原尺寸转 45° → 斜矩形（刚体 ⇒ 画布变换）
 *   · 右上 (700,150) 放大 2 倍    → 200×120（**非刚体 ⇒ 逐点变换**，两条路都走这条）
 *   · 右下 (700,400) 放大 2 倍转 30° → 更大的斜矩形（非刚体 + 旋转）
 *
 * ⚠ 形状与位置**一项都不许变**：这张图在"画布变换开"与"画布变换关"两种构建下
 *   必须逐像素相同（唯一允许的差异是抗锯齿边缘的亚像素抖动）。
 */
#include <waycoder_ui.h>

int main() {
    int b;

    ui_win_open("旋转对照", ui_scr_w(), ui_scr_h());

    /* 图块：实心蓝底 + 白色空心描边（描边用来验证"轮廓在旋转下没变形"） */
    b = ui_create_block(100, 60, 0);
    ui_rect(0, 0, 100, 60, 0xFF44AAFF, 1, 0, 0);
    ui_rect(0, 0, 100, 60, 0xFFFFFFFF, 0, 2, 0);
    ui_end_block();

    for (;;) {
        if (ui_win_closed() != 0) { break; }

        ui_clear(0xFF101018);

        /* ⚠ 坐标必须落在**场景内**（`ui_scr_w/h` 给的尺寸），而且躲开顶部那块
         *   VM 状态浮层 —— 用 x=700 那种"屏幕坐标"的写法会让图块画到画布外面，
         *   截图上就只剩一半，白查一轮。 */

        /* ── 刚体：旋转 → 走画布变换 + 平台原生 ── */
        ui_draw_block(b, 100, 300, 1000, 1000, 0);
        ui_draw_block(b, 100, 450, 1000, 1000, 90);
        ui_draw_block(b, 100, 580, 1000, 1000, 45);

        /* ── 非刚体：缩放 → 走逐点变换（两条构建都走这条，作为"不变"的参照）── */
        ui_draw_block(b, 280, 300, 2000, 2000, 0);
        ui_draw_block(b, 280, 500, 2000, 2000, 30);

        ui_present();
        ui_wait_msg(2000);
    }
    return 0;
}
