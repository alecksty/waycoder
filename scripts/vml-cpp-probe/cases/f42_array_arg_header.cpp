// F42（原 OPEN #15）：数组名当实参要跳过 4 字节长度头
//
// 症状：`ui_polygon(pts, n, …)` 从 C++ 拿到的点全是 `(长度,0),(0,0)…`
//   ⇒ 画出来是"从 (0,0) 甩出去的尖锥"。而**传进去的地址是对的、宿主参数也是对的**，
//   差的是那 4 字节长度头（索引路径自己会 +4 补上，传参这一路没补）。
//
// 判据取"求和"而不是"看画面对不对"：画面要人眼看，求和是数字、一跑就知道。
//   全局数组的头里存着长度（`g[3]` 头 = 3），所以旧行为会**多读一个 3** ⇒ 33；
//   局部数组的头是 0 ⇒ 3。两个数各自都有特征，一眼能认出是"多读了一格"。
#include <waycoder_ui.h>
int gsum(int* p) { return p[0] + p[1] + p[2]; }
int g[3];
int main() {
    int l[3];
    l[0] = 1; l[1] = 2; l[2] = 3;
    g[0] = 10; g[1] = 20; g[2] = 30;
    int a = gsum(l);
    int b = gsum(g);
    if (a != 6) { cout << "局部数组传参不对 local=" << a << "（应 6）" << endl; return 1; }
    if (b != 60) { cout << "全局数组传参不对 global=" << b << "（应 60）" << endl; return 1; }
    cout << "ALL PASS" << endl;
    return 0;
}
